const {app,BrowserWindow,protocol,net}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),assets=path.join(root,'android/app/src/main/assets/app');
const run=Date.now().toString();
process.env.TOZ_ANDROID_TEST_DIR=path.join(root,'.runtime','android-ui-'+run);
fs.mkdirSync(process.env.TOZ_ANDROID_TEST_DIR,{recursive:true});
const output=path.join(root,'artifacts/android-ui');fs.mkdirSync(output,{recursive:true});
app.setPath('userData',path.join(process.env.TOZ_ANDROID_TEST_DIR,'electron'));
protocol.registerSchemesAsPrivileged([{scheme:'toz',privileges:{standard:true,secure:true,supportFetchAPI:true}}]);
app.whenReady().then(async()=>{
  let win;const errors=[],checks=[];
  try{
    protocol.handle('toz',request=>net.fetch(pathToFileURL(path.join(assets,new URL(request.url).pathname)).href));
    win=new BrowserWindow({width:390,height:844,show:false,useContentSize:true,webPreferences:{preload:path.join(__dirname,'test-preload.cjs'),contextIsolation:false,nodeIntegration:false,sandbox:false,offscreen:true,backgroundThrottling:false}});
    win.webContents.on('console-message',(_event,level,message)=>{if(level===3)errors.push(message);});
    const js=code=>win.webContents.executeJavaScript(code,true);
    const capture=async name=>{await js('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');await new Promise(resolve=>setTimeout(resolve,200));fs.writeFileSync(path.join(output,name),(await win.webContents.capturePage()).toPNG());};
    const wait=async code=>{for(let i=0;i<60;i++){if(await js(code))return;await new Promise(resolve=>setTimeout(resolve,100));}throw new Error('Timed out: '+code);};
    const check=(name,result)=>{assert.ok(result,name);checks.push(name);};
    await win.loadURL('toz://app/index.html');await wait('!!document.querySelector(".mobile-tabs")');
    check('empty native SQLite startup',await js('window.toz.read().ok && window.toz.read().snapshot.tasks.length===0'));
    check('real current local date',await js('document.querySelector("#date-label").textContent.includes(new Date().getDate())'));
    await js('document.querySelector(".toolbar-add").click()');
    check('phone new-task dialog',await js('document.querySelector("#new-dialog").open'));
    await js(`(()=>{const f=document.querySelector('#new-form');f.elements.title.value='安卓待办验收';f.requestSubmit();})()`);
    await wait('window.toz.read().snapshot.tasks.length===1');
    await js(`document.querySelector('[data-mobile-view="all"]').click()`);
    await wait('document.querySelector("#task-list").textContent.includes("安卓待办验收")');
    check('phone viewport has no horizontal overflow',await js('document.documentElement.scrollWidth<=innerWidth'));
    await js(`document.querySelector('#task-list [data-action="select"]').click()`);
    check('phone detail opens',await js('document.documentElement.classList.contains("mobile-detail") && getComputedStyle(document.querySelector("#task-detail")).display!=="none"'));
    check('back closes detail',await js('window.tozMobileBack() && !document.documentElement.classList.contains("mobile-detail")'));
    await js('document.querySelector("#mobile-menu").click()');
    check('phone navigation drawer',await js('document.documentElement.classList.contains("mobile-drawer")'));
    await js('window.tozMobileBack();document.querySelector("#mobile-settings").click()');
    check('mobile settings opens',await js('document.querySelector("#settings-dialog").open'));
    check('Windows startup settings hidden',await js('getComputedStyle(document.querySelector("[data-settings-tab=startup]")).display==="none"'));
    await js('window.tozMobileBack()');
    await capture('phone-dark.png');
    await js('document.querySelector("#mobile-settings").click();document.querySelector("[data-action=theme-light]").click();window.tozMobileBack()');
    await wait('document.documentElement.dataset.theme==="light" && !document.querySelector("#settings-dialog").open');
    await capture('phone-light.png');
    for(const [name,width,height] of [['tablet-portrait',800,1100],['tablet-landscape',1280,800]]){
      win.setContentSize(width,height);await new Promise(resolve=>setTimeout(resolve,200));
      check(name+' no horizontal overflow',await js('document.documentElement.scrollWidth<=innerWidth'));
      await js('document.querySelector("[data-mobile-view=calendar]").click()');
      check(name+' calendar',await js('!document.querySelector("#calendar-view").hidden'));
      await capture(name+'.png');
      await js('document.querySelector("[data-mobile-view=all]").click()');
    }
    win.setContentSize(390,844);
    await new Promise(resolve=>setTimeout(resolve,250));
    await js('document.querySelector("#mobile-menu").click();document.querySelector(".project-edit").click()');
    check('touch project menu exposes edit and delete',await js('!!document.querySelector(".context-menu:not([hidden]) [data-context-command=delete-project]")'));
    await js('document.querySelector("[data-context-command=edit-project]").click()');
    check('touch project edit dialog',await js('document.querySelector("#project-dialog").open'));
    await js('window.tozMobileBack();window.tozMobileBack();document.querySelector("#task-list [data-action=select]").click();document.querySelector("#task-detail [data-action=start]").click()');
    check('start records actual start on phone',await js('!!window.toz.read().snapshot.tasks[0].started'));
    await js('document.querySelector("#task-detail [data-action=complete]").click()');
    check('complete on phone',await js('window.toz.read().snapshot.tasks[0].done'));
    await js('document.querySelector("#task-detail [data-action=complete]").click();window.tozMobileBack();document.querySelector("#task-list [data-action=more]").click();document.querySelector("[data-context-command=delete-task]").click()');
    check('touch task delete preserves trash',await js('!!window.toz.read().snapshot.tasks[0].deletedAt'));
    await js('document.querySelector("[data-action=app-menu]").click();document.querySelector("[data-context-command=app-trash]").click()');
    check('phone trash accessible from app menu',await js('document.querySelector("#trash-dialog").open'));
    await js('document.querySelector("[data-restore=task]").click()');
    check('phone restore keeps start and history',await js('!window.toz.read().snapshot.tasks[0].deletedAt && !!window.toz.read().snapshot.tasks[0].started && window.toz.read().snapshot.tasks[0].events.some(e=>e.type==="task_restore")'));
    await js('window.tozMobileBack();document.querySelector("[data-mobile-view=calendar]").click()');
    check('phone calendar fits seven days',await js('document.querySelector(".calendar-board").getBoundingClientRect().width<=innerWidth'));
    await capture('phone-calendar.png');
    await js('document.querySelector("[data-action=calendar-select]").click()');
    check('phone calendar opens task detail',await js('document.documentElement.classList.contains("mobile-detail") && !document.querySelector("#task-detail").hidden && getComputedStyle(document.querySelector("#task-detail")).display!=="none"'));
    await js('window.tozMobileBack();document.querySelector("[data-view=gantt]").click();document.querySelector("[data-gantt=select]").click()');
    check('phone gantt opens task detail',await js('document.documentElement.classList.contains("mobile-detail") && !document.querySelector("#task-detail").hidden'));
    await win.reload();await wait('!!document.querySelector(".mobile-tabs")');
    check('task persists after restart',await js('window.toz.read().snapshot.tasks[0].title==="安卓待办验收"'));
    check('no renderer console errors',errors.length===0);
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({ok:true,checks,errors},null,2));console.log(JSON.stringify({ok:true,checks,output},null,2));
    win.destroy();app.exit(0);
  }catch(error){console.error(error);fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({ok:false,checks,errors,error:error.stack},null,2));try{if(win)fs.writeFileSync(path.join(output,'failure.png'),(await win.webContents.capturePage()).toPNG());}catch{}finally{if(win)win.destroy();app.exit(1);}}
});
